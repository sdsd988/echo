-- V1: 초기 스키마 (H2 create-drop → Flyway 이관)
-- 기존 JPA 엔티티 매핑을 그대로 옮긴다. Hibernate ddl-auto=validate가 이 스키마를 검증한다.
-- CREATE TABLE IF NOT EXISTS로 멱등하게 작성한다.

-- user 모듈 — com.echo.user.domain.User
CREATE TABLE IF NOT EXISTS users (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(50)  NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    created_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username)
);

-- post 모듈 — com.echo.post.domain.Post
CREATE TABLE IF NOT EXISTS posts (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id  BIGINT       NOT NULL,
    content    VARCHAR(280) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

-- follow 모듈 — com.echo.follow.domain.Follow
CREATE TABLE IF NOT EXISTS follows (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT       NOT NULL,
    followee_id BIGINT       NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_follow_follower_followee UNIQUE (follower_id, followee_id)
);

-- engagement 모듈 — com.echo.engagement.domain.Like
CREATE TABLE IF NOT EXISTS likes (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT       NOT NULL,
    user_id    BIGINT       NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_like_post_user UNIQUE (post_id, user_id)
);

