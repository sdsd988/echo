-- V2: moderation 모듈 — 콘텐츠 안전(금칙어 필터 + 신고)
-- Hibernate ddl-auto=validate가 이 스키마를 엔티티 매핑과 대조 검증한다.
-- CREATE TABLE IF NOT EXISTS로 멱등하게 작성한다.

-- 금칙어 — com.echo.moderation.domain.BannedWord
-- 목록은 DB로 관리한다(애플리케이션 하드코딩 금지). 초기 시드는 아래 INSERT로 넣는다.
CREATE TABLE IF NOT EXISTS banned_words (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word       VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_banned_word UNIQUE (word)
);

-- 신고 — com.echo.moderation.domain.Report
-- status: PENDING → REVIEWED → RESOLVED (전이 규칙은 도메인이 강제)
CREATE TABLE IF NOT EXISTS reports (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT       NOT NULL,
    target_type VARCHAR(20)  NOT NULL,
    target_id   BIGINT       NOT NULL,
    reason      VARCHAR(500) NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL
);

-- 초기 금칙어 시드(데모/테스트용). 운영에서는 별도 관리 화면으로 증감한다.
-- 이미 있으면 건너뛰어 멱등하게 둔다.
INSERT INTO banned_words (word, created_at)
SELECT v.word, CURRENT_TIMESTAMP
FROM (VALUES ('비속어'), ('욕설'), ('badword')) AS v(word)
WHERE NOT EXISTS (SELECT 1 FROM banned_words b WHERE b.word = v.word);
